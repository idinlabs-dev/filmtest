List<Drama> getDramasByGenre(String genre) {
  if (genre == 'All') return dummyDramas;
  return dummyDramas.where((d) => d.genres.contains(genre)).toList();
}

List<Drama> searchDramas(String query) {
  final lowerQuery = query.toLowerCase();
  return dummyDramas.where((d) =>
    d.title.toLowerCase().contains(lowerQuery) ||
    d.originalTitle.toLowerCase().contains(lowerQuery) ||
    d.description.toLowerCase().contains(lowerQuery) ||
    d.mainCast.any((c) => c.toLowerCase().contains(lowerQuery)) ||
    d.genres.any((g) => g.toLowerCase().contains(lowerQuery))
  ).toList();
}